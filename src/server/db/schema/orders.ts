/**
 * The authoritative order state machine, as data.
 *
 * Read twice for different purposes: the domain layer asks whether *this actor* may
 * make *this move*, and the `orders_guard_state_transition` trigger asks whether the
 * move exists at all. Terminal states simply have no outgoing rows, and admin
 * overrides are explicit rows rather than a wildcard — so no SQL path, including a
 * hand-written admin fix, can teleport an order into `collected`.
 */
export const orderStateTransitions = pgTable(
  'order_state_transitions',
  {
    fromState: orderStateEnum('from_state').notNull(),
    toState: orderStateEnum('to_state').notNull(),
    /** Who may make this move: 'customer' | 'shop' | 'admin' | 'system' | 'provider'. */
    actorTypes: text('actor_types')
      .array()
      .$type<('customer' | 'shop' | 'admin' | 'system' | 'provider')[]>()
      .notNull(),
    /** Whether the domain layer must record a reason on the resulting event. */
    requiresReason: boolean('requires_reason').notNull().default(false),
    note: text('note').notNull(),
  },
  (t) => [primaryKey({ columns: [t.fromState, t.toState] })],
)

