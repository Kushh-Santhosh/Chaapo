/**
 * Orders — mirrors `db/migrations/0006_orders.sql`, plus `order_state_transitions`
 * from `0010_immutability_and_guards.sql`.
 *
 * The order is the contract between a customer and a shop, and four decisions in
 * the SQL defend it. They are worth knowing before you write a query here:
 *
 *   • **The price is a snapshot.** Every agreed amount is copied onto the order at
 *     placement and then frozen by trigger. A change to a price list, a commission
 *     rate or a tax rate cannot alter a placed order (PRD §F inv. 6, FR-320).
 *   • **The money adds up, by constraint.** `total = subtotal - discount + surcharge
 *     + platformFee + tax`, and `shopPayable + commission + commissionTax +
 *     platformFee = total`. Unassigned money is unrepresentable (PRD §38.4).
 *   • **State changes are events.** `orderEvents` is append-only with a per-order
 *     monotonic `sequence`, so it is at once the audit trail, the customer timeline
 *     and the durable SSE outbox replayed after a reconnect (FR-410, NFR-16).
 *   • **The pickup code is a secret.** Only a keyed hash is stored for comparison;
 *     the displayable copy is encrypted. Reading the database does not let you
 *     collect someone else's documents (FR-425, NFR-14).
 */

