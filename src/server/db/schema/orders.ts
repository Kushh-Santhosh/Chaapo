/**
 * Only a collected order can be rated, so a rating is always attached to a real
 * transaction. That one rule removes most review spam without a moderation team
 * (FR-701) — and it is enforced by trigger, not by convention.
 */
export const orderRatings = pgTable('order_ratings', {
  id: id(),
  orderId: uuid('order_id')
    .notNull()
    .references(() => orders.id, { onDelete: 'cascade' }),
  shopId: uuid('shop_id')
    .notNull()
    .references(() => shops.id, { onDelete: 'cascade' }),
  userId: uuid('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  stars: smallint('stars').notNull(),
  /** Structured feedback, so "3 people mentioned print quality" needs no NLP. */
  tags: text('tags').array().notNull().default([]),
  comment: text('comment'),
  isPublic: boolean('is_public').notNull().default(true),
  moderationState: text('moderation_state')
    .$type<'published' | 'pending_review' | 'hidden' | 'removed'>()
    .notNull()
    .default('published'),
  moderatedBy: uuid('moderated_by').references(() => users.id),
  moderatedAt: tstz('moderated_at'),
  moderationReason: text('moderation_reason'),
  /** The shop's one reply. */
  shopReply: text('shop_reply'),
  shopRepliedAt: tstz('shop_replied_at'),
  ...timestamps,
})
